#!/usr/bin/env python3
"""Render every screen to an HTML page, from the code the device runs.

The first set of mockups were hand-drawn SVG, which meant they could - and did
- promise things the device could not do. These are generated by running the
real screens through the real harness and turning the draw calls into SVG, so a
mockup that disagrees with the display is now impossible.

    python3 tools/mockup.py [out.html]
"""
import os
import sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "davega-gui")
sys.path.insert(0, os.path.abspath(ROOT))

from harness.display import Display, rgb565_to_rgb, glyph_size   # noqa: E402
from harness.telemetry import Board                              # noqa: E402
from screens.app import App, Menu, MenuItem                      # noqa: E402
from screens.riding import Riding                                # noqa: E402
from screens.panels import (RangeScreen, OverviewScreen,         # noqa: E402
                            SessionScreen, LifetimeScreen)
from screens.startup import Splash                               # noqa: E402
from screens.themes import THEMES                                # noqa: E402

W, H = 240, 320
SCREENS = (("riding", Riding), ("range", RangeScreen),
           ("overview", OverviewScreen), ("session", SessionScreen),
           ("lifetime", LifetimeScreen))
NAMES = tuple(n for n, _ in SCREENS)


def hexc(c):
    return "#%02x%02x%02x" % rgb565_to_rgb(c)


class SvgDisplay(Display):
    """Records the same calls, and can emit them as SVG.

    Filled rectangles - which is how bigfont draws digits - come out exactly.
    Label text becomes real SVG text rather than the solid blocks the harness
    uses for layout testing, so the page is readable.
    """

    def __init__(self):
        Display.__init__(self, strict=False)
        self.ops = []

    def erase(self):
        self.ops.append(("bg", self.bg))
        Display.erase(self)

    def fill_rectangle(self, x, y, w, h, color=None):
        self.ops.append(("rect", x, y, w, h,
                         self.color if color is None else color))
        Display.fill_rectangle(self, x, y, w, h, color)

    def print(self, text, scale=1, numeric=None):
        cw, ch = glyph_size(str(text), scale, numeric)
        self.ops.append(("text", self.pos[0], self.pos[1], str(text), cw, ch,
                         self.color))
        Display.print(self, text, scale, numeric)

    def svg(self):
        out = ['<svg viewBox="0 0 %d %d" width="%d" height="%d">' % (W, H, W, H)]
        bg = "#000000"
        for op in self.ops:
            if op[0] == "bg":
                bg = hexc(op[1])
        out.append('<rect width="%d" height="%d" fill="%s"/>' % (W, H, bg))
        for op in self.ops:
            if op[0] == "rect":
                _, x, y, w, h, c = op
                out.append('<rect x="%d" y="%d" width="%d" height="%d" fill="%s"/>'
                           % (x, y, w, h, hexc(c)))
            elif op[0] == "text":
                _, x, y, t, cw, ch, c = op
                out.append('<text x="%d" y="%d" fill="%s" font-size="%d" '
                           'font-family="ui-monospace,Menlo,monospace" '
                           'letter-spacing="%.1f" xml:space="preserve">%s</text>'
                           % (x, y + ch - 1, hexc(c), ch + 1, cw - ch * 0.6,
                              t.replace("&", "&amp;").replace("<", "&lt;")))
        out.append("</svg>")
        return "".join(out)


def frame(board):
    """A believable moment: 25 km/h, pulling 18 A, pack a third down."""
    f = board.nominal()
    f["rpm"] = board.erpm_for_kph(25.0)
    f["avg_motor_current"] = 18.0
    f["avg_input_current"] = 9.5
    f["input_voltage"] = 45.8
    f["temp_fet_filtered"] = 42.0
    f["temp_motor_filtered"] = 48.0
    f["s_range_km"] = 21.0
    f["gear"] = 3
    return f


def render_all(theme):
    board = Board()
    f = frame(board)
    shots = []
    for i, (name, cls) in enumerate(SCREENS):
        d = SvgDisplay()
        s = cls(theme, NAMES, i)
        for _ in range(30):
            s.render(d, f, board, full=(not s._drawn))
            if not hasattr(s, "settled") or s.settled():
                break
        shots.append((name, cls.title, d.svg()))

    d = SvgDisplay()
    sp = Splash(theme)
    sp.render(d, f, board, full=True)
    for _ in range(9):
        sp.render(d, f, board)
    shots.insert(0, ("startup", "POWER ON", d.svg()))

    d = SvgDisplay()
    app = App(SCREENS, board, theme,
              Menu([MenuItem("Theme", ["nazare", "rosso", "papaya"]),
                    MenuItem("Display", ["night", "day"])]), sweep=False)
    app.press("enter")
    app.render(d, f)
    shots.append(("menu", "MENU", d.svg()))
    return shots


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else "davega-gui/mockups/screens.html"
    theme = sys.argv[2] if len(sys.argv) > 2 else "nazare"
    shots = render_all(theme)
    t = THEMES[theme]
    cards = "".join(
        '<figure><div class="screen">%s</div>'
        '<figcaption><b>%s</b><span>%s</span></figcaption></figure>'
        % (svg, title, key) for key, title, svg in shots)
    html = """<title>%s screens</title>
<style>
 :root { color-scheme: dark; }
 body { background:#0b0d10; color:#e8ecf4; margin:0;
        font:14px/1.5 ui-sans-serif,system-ui,sans-serif; }
 .wrap { max-width:1180px; margin:0 auto; padding:36px 24px 64px; }
 h1 { font-size:30px; margin:0 0 6px; letter-spacing:-.01em; }
 .sub { color:#7a8496; margin:0 0 28px; max-width:64ch; }
 .grid { display:grid; gap:26px; grid-template-columns:repeat(auto-fill,minmax(272px,1fr)); }
 figure { margin:0; background:#14171c; border:1px solid #262b33; }
 .screen { padding:16px; display:flex; justify-content:center; background:#000; }
 figcaption { display:flex; align-items:baseline; gap:10px; padding:10px 14px;
              border-top:1px solid #262b33; }
 figcaption b { font-size:15px; }
 figcaption span { margin-left:auto; color:#6c7688;
                   font:11px ui-monospace,Menlo,monospace; }
 code { font:12px ui-monospace,Menlo,monospace; color:#9fb0c6; }
</style>
<div class="wrap">
<h1>%s &mdash; every screen</h1>
<p class="sub">Generated from the screen code by <code>tools/mockup.py</code>,
at true device size (240&times;320). Rectangles are exactly what the display
draws; the large digits are the 3&times;5 font rendered as rectangles, which is
how they are drawn on the panel. Small labels are set in a monospace face here
rather than as solid blocks, so the page is readable &mdash; on the device they
are the firmware's own 8&times;8 font.</p>
<div class="grid">%s</div>
</div>""" % (t.name, t.name, cards)
    with open(out, "w") as fh:
        fh.write(html)
    print("wrote %s (%d screens, theme %s)" % (out, len(shots), theme))


if __name__ == "__main__":
    main()
